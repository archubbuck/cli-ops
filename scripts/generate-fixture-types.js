#!/usr/bin/env node
/**
 * Generate TypeScript types for fixtures
 * Scans fixture directories and creates type-safe imports
 */

import { readdir, readFile, writeFile, stat } from 'node:fs/promises'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { dirname } from 'node:path'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)

const FIXTURES_DIR = join(__dirname, '../libs/shared-testing/fixtures')
const OUTPUT_FILE = join(__dirname, '../libs/shared-testing/src/fixture-types.ts')

/**
 * Scan directory recursively for fixture files
 */
async function scanFixtures(dir, base = dir) {
  const fixtures = []
  const entries = await readdir(dir, { withFileTypes: true })

  for (const entry of entries) {
    const fullPath = join(dir, entry.name)

    if (entry.isDirectory()) {
      // Recursively scan subdirectories
      const subFixtures = await scanFixtures(fullPath, base)
      fixtures.push(...subFixtures)
    } else if (entry.isFile() && entry.name.endsWith('.json')) {
      // Add JSON fixtures
      const relativePath = relative(base, fullPath)
      const importPath = relativePath.split(sep).join('/')

      fixtures.push({
        path: importPath,
        name: generateTypeName(relativePath),
        version: await extractVersion(fullPath),
      })
    }
  }

  return fixtures
}

/**
 * Generate a TypeScript-safe type name from a file path
 */
function generateTypeName(path) {
  return path
    .replace(/\.(json|yaml|yml)$/, '')
    .replace(/[\/\\]/g, '_')
    .replace(/[^a-zA-Z0-9_]/g, '')
    .replace(/^(\d)/, '_$1') // Prefix with _ if starts with number
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
    .concat('Fixture')
}

/**
 * Extract version from fixture file
 */
async function extractVersion(path) {
  try {
    const content = await readFile(path, 'utf-8')
    const data = JSON.parse(content)
    return data.version || 'unknown'
  } catch {
    return 'unknown'
  }
}

/**
 * Generate TypeScript type definitions
 */
function generateTypes(fixtures) {
  const header = `/**
 * Auto-generated fixture type definitions
 * DO NOT EDIT MANUALLY
 * Generated by: scripts/generate-fixture-types.js
 */

/* eslint-disable */
// @ts-nocheck

`

  const imports = `import type { 
  ConfigFixture, 
  TaskFixture, 
  APIResponseFixture, 
  GitRepoFixture 
} from '@cli-ops/shared-types'

`

  const typeMap = `/**
 * Map of fixture paths to their types
 */
export interface FixtureTypeMap {
${fixtures.map((f) => `  '${f.path}': ${inferType(f.path)}`).join('\n')}
}

`

  const fixtureList = `/**
 * Available fixtures with metadata
 */
export const AVAILABLE_FIXTURES = ${JSON.stringify(
    fixtures.map((f) => ({ path: f.path, version: f.version })),
    null,
    2,
  )} as const

`

  const helpers = `/**
 * Get fixture type by path
 */
export type GetFixtureType<P extends keyof FixtureTypeMap> = FixtureTypeMap[P]

/**
 * All fixture paths
 */
export type FixturePath = keyof FixtureTypeMap
`

  return header + imports + typeMap + fixtureList + helpers
}

/**
 * Infer TypeScript type from fixture path
 */
function inferType(path) {
  if (path.includes('config')) return 'ConfigFixture'
  if (path.includes('task')) return 'TaskFixture'
  if (path.includes('api-response')) return 'APIResponseFixture'
  if (path.includes('git-repo')) return 'GitRepoFixture'
  return 'unknown'
}

/**
 * Main function
 */
async function main() {
  try {
    console.log('🔍 Scanning fixtures directory...')
    const fixtures = await scanFixtures(FIXTURES_DIR)

    console.log(`📝 Found ${fixtures.length} fixtures`)

    console.log('✨ Generating type definitions...')
    const types = generateTypes(fixtures)

    console.log(`💾 Writing to ${relative(process.cwd(), OUTPUT_FILE)}`)
    await writeFile(OUTPUT_FILE, types, 'utf-8')

    console.log('✅ Fixture types generated successfully!')
  } catch (error) {
    console.error('❌ Error generating fixture types:', error.message)
    process.exit(1)
  }
}

main()
